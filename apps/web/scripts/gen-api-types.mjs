#!/usr/bin/env node
/**
 * Generate src/types/api.generated.ts from the API OpenAPI schema.
 *
 *   pnpm gen:types                         # from $OPENAPI_URL or $NEXT_PUBLIC_API_URL/openapi.json
 *   pnpm gen:types -- --input ../api/openapi.json
 *   pnpm check:types                       # CI: fail if the committed file is stale
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(root, "src/types/api.generated.ts");
const args = process.argv.slice(2);
const check = args.includes("--check");
const inputIdx = args.indexOf("--input");
const inputArg = inputIdx >= 0 ? args[inputIdx + 1] : undefined;

function resolveSource() {
  if (inputArg) return pathToFileURL(resolve(process.cwd(), inputArg));
  if (process.env.OPENAPI_URL) return new URL(process.env.OPENAPI_URL);
  if (process.env.NEXT_PUBLIC_API_URL)
    return new URL("/openapi.json", process.env.NEXT_PUBLIC_API_URL);
  return pathToFileURL(resolve(root, "../api/openapi.json"));
}

const source = resolveSource();
const header =
  "/**\n * GENERATED by scripts/gen-api-types.mjs from the API OpenAPI schema. Do not edit.\n */\n\n";
const ast = await openapiTS(source);
const output = header + astToString(ast);

if (check) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  if (current !== output) {
    console.error(`src/types/api.generated.ts is stale vs ${source}. Run pnpm gen:types.`);
    process.exit(1);
  }
  console.log("API types are up to date.");
} else {
  await writeFile(outFile, output);
  console.log(`Wrote ${outFile} from ${source}`);
}
